import { test, expect } from '@playwright/test'
import { execFileSync } from 'node:child_process'
import { resolve } from 'node:path'

test('文件目录、版本切换、物理清理和平台管理', async ({ page }) => {
  test.setTimeout(120000)
  page.setDefaultTimeout(15000)
  const suffix = Date.now().toString().slice(-8)
  const username = 'files_' + suffix
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  const phone = '136' + suffix
  const clientIp = '127.' + [0, 2, 4].map(i => Number(suffix.slice(i, i + 2)) + 1).join('.')
  const sms = await page.request.post('/api/auth/sms', { data: { phone }, headers: { 'x-forwarded-for': clientIp } })
  expect(sms.ok()).toBe(true)
  const registered = await page.request.post('/api/auth/register', { data: { username, full_name: '文件测试用户', phone, code: (await sms.json()).development_code, password: 'FilesTestPassword!' }, headers: { 'x-forwarded-for': clientIp } })
  expect(registered.ok()).toBe(true)
  const python = resolve('.venv/Scripts/python.exe')
  const zip = execFileSync(python, ['-c', "import io,zipfile,sys;b=io.BytesIO()\nwith zipfile.ZipFile(b,'w') as z:z.writestr('index.html','<html><title>Files V1</title><h1>Files V1</h1></html>');z.writestr('assets/images/logo.txt','x'*2048);z.writestr('assets/css/site.css','body{}')\nsys.stdout.buffer.write(b.getvalue())"])
  async function upload(name: string, buffer: Buffer, pageId = '') {
    const response = await page.request.post('/api/uploads', { multipart: { file: { name, mimeType: name.endsWith('.zip') ? 'application/zip' : 'text/html', buffer }, menu_path: JSON.stringify(['文件测试', '示例']), ...(pageId ? { page_id: pageId } : {}) } })
    expect(response.status()).toBe(202)
    const job = await response.json()
    await expect.poll(async () => (await (await page.request.get('/api/uploads/' + job.id)).json()).status, { timeout: 20000 }).toBe('success')
    return (await (await page.request.get('/api/uploads/' + job.id)).json()).result
  }
  const v1 = await upload('files-v1.zip', zip)
  const v2 = await upload('files-v2.html', Buffer.from('<html><title>Files V2</title><h1>Files V2</h1></html>'), v1.page_id)
  const v3 = await upload('files-v3.html', Buffer.from('<html><title>Files V3</title><h1>Files V3</h1></html>'), v1.page_id)
  await page.goto('/?view=files')
  const manager = page.getByRole('region', { name: '文件管理', exact: true })
  await expect(page.getByRole('heading', { name: '文件管理', exact: true })).toBeVisible()
  await expect(manager.locator('.el-table__body tbody tr')).toHaveCount(3)
  const v1Row = manager.getByRole('row').filter({ hasText: 'files-v1.zip' })
  await expect(v1Row).toContainText('已挂接')
  await expect(v1Row).toContainText('历史版本')
  const singleDownload = page.waitForEvent('download')
  await v1Row.getByRole('button', { name: '下载原件', exact: true }).click()
  expect((await singleDownload).suggestedFilename()).toBe('files-v1.zip')
  await v1Row.locator('.el-checkbox').click()
  const batchDownload = page.waitForEvent('download')
  await manager.getByRole('button', { name: /批量下载/ }).click()
  expect((await batchDownload).suggestedFilename()).toBe('PageHub-上传文件.zip')
  await v1Row.locator('.el-checkbox').click()
  await expect(manager.getByRole('complementary', { name: '文件目录' })).toContainText('文件测试')
  await v1Row.getByRole('button', { name: '文件清单', exact: true }).click()
  const drawer = page.getByRole('dialog', { name: /files-v1.zip.*文件清单/ })
  await expect(drawer).toContainText('assets/images/logo.txt')
  await expect(drawer).toContainText('2.0 KB')
  await drawer.locator('.el-select__wrapper').click()
  await page.getByRole('option', { name: /assets\/images \(2.0 KB\)/ }).click()
  await expect(drawer.locator('.el-table__body tbody tr')).toHaveCount(1)
  await page.screenshot({ path: '.runtime/files-manifest-light.png', animations: 'disabled' })
  await drawer.getByRole('button', { name: /Close this dialog|关闭此对话框/ }).click()
  const v2Row = manager.getByRole('row').filter({ hasText: 'files-v2.html' })
  await v2Row.getByRole('button', { name: '文件操作', exact: true }).click()
  await page.getByRole('menuitem', { name: '设为当前版本', exact: true }).click()
  await page.getByRole('button', { name: '确认切换', exact: true }).click()
  await expect(v2Row).toContainText('当前版本')
  const v3Row = manager.getByRole('row').filter({ hasText: 'files-v3.html' })
  await expect(v3Row).toContainText('历史版本')
  await page.getByRole('button', { name: '切换深色主题', exact: true }).click()
  await expect(page.locator('html')).toHaveClass('dark')
  await expect(manager.locator('.el-loading-mask:visible')).toHaveCount(0)
  await expect(manager.locator('.el-table__body tbody tr')).toHaveCount(3)
  await page.screenshot({ path: '.runtime/files-manager-dark.png', animations: 'disabled' })
  await v1Row.locator('.el-checkbox').click()
  await v3Row.locator('.el-checkbox').click()
  await manager.getByRole('button', { name: /删除所选历史版本/ }).click()
  await expect(page.getByRole('dialog', { name: '彻底删除历史版本', exact: true })).toContainText('2 个历史版本')
  await page.getByRole('button', { name: '彻底删除', exact: true }).click()
  await expect(v1Row).toContainText('文件已删除', { timeout: 20000 })
  await expect(v3Row).toContainText('文件已删除', { timeout: 20000 })
  await expect.poll(async () => (await (await page.request.get('/api/workspace')).json()).storage.used_bytes).toBe(v2.size_bytes)
  await manager.getByText('清理任务', { exact: true }).click()
  await expect(manager.locator('.el-table__body tbody tr')).toHaveCount(2)
  await expect(manager.locator('.el-table__body')).toContainText('已完成')
  await page.screenshot({ path: '.runtime/files-cleanup-dark.png', animations: 'disabled' })
  await manager.getByText('上传文件', { exact: true }).click()
  await page.setViewportSize({ width: 390, height: 844 })
  await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.screenshot({ path: '.runtime/files-manager-mobile.png', animations: 'disabled' })
  await page.setViewportSize({ width: 1440, height: 1000 })
  const lightRefresh = page.waitForResponse(response => new URL(response.url()).pathname === '/api/files' && response.ok())
  await page.getByRole('button', { name: '切换浅色主题', exact: true }).click()
  await lightRefresh
  await expect(page.locator('html')).not.toHaveClass('dark')
  await expect(manager.locator('.el-loading-mask:visible')).toHaveCount(0)
  await page.screenshot({ path: '.runtime/files-manager-light.png', animations: 'disabled' })
  await v2Row.getByRole('button', { name: '文件操作', exact: true }).click()
  await page.getByRole('menuitem', { name: '彻底删除页面及文件', exact: true }).click()
  await expect(page.getByRole('dialog', { name: '彻底删除页面及文件', exact: true })).toContainText('全部 1 个保留版本')
  await page.getByRole('button', { name: '彻底删除', exact: true }).click()
  await expect(v2Row).toContainText('文件已删除', { timeout: 20000 })
  await expect.poll(async () => (await (await page.request.get('/api/workspace')).json()).storage.used_bytes).toBe(0)
  expect((await page.request.get('/api/pages/' + v1.page_id + '/preview')).status()).toBe(404)
  await page.getByRole('button', { name: '工作台设置', exact: true }).click()
  await page.getByRole('navigation', { name: '工作台功能' }).getByRole('button', { name: '上传记录', exact: true }).click()
  await expect(page.locator('.el-table__body tbody tr')).toHaveCount(3)
  await expect(page.locator('.el-table__body')).toContainText('文件已删除')
  await page.getByRole('row').filter({ hasText: 'files-v1.zip' }).getByRole('button', { name: '管理文件', exact: true }).click()
  await expect(manager).toBeVisible()
  await expect(manager).toContainText('已筛选此页面的全部版本')
  await page.reload()
  await expect(manager).toContainText('已筛选此页面的全部版本')
  await manager.locator('.file-actions > .el-tag .el-tag__close').click()
  await expect(page).not.toHaveURL(/file_page=/)
  await page.reload()
  await expect(manager.locator('.file-actions > .el-tag')).toHaveCount(0)
  // 仅提升本测试账号，验证平台入口后恢复角色。
  execFileSync(python, ['-c', "import sys;sys.path.insert(0,'backend');from app.db import pool,transaction;pool.open(wait=True)\nwith transaction(admin=True) as c:c.execute(\"UPDATE users SET role='superadmin' WHERE username=%s\",(sys.argv[1],))\npool.close()", username])
  try {
    await page.goto('/?view=admin&admin=files')
    await expect(page.getByRole('navigation', { name: '平台管理导航' }).getByRole('button', { name: '文件管理', exact: true })).toBeVisible()
    await expect(page.getByRole('combobox', { name: '文件租户' })).toBeVisible()
    await expect(page.getByRole('combobox', { name: '文件上传者' })).toBeVisible()
    await page.getByPlaceholder('搜索文件名或页面名称').fill('files-v1.zip')
    const matches = (await (await page.request.get('/api/files?platform=true&q=files-v1.zip')).json()).total
    expect(matches).toBeGreaterThan(0)
    await expect(manager.locator('.el-table__body tbody tr')).toHaveCount(matches)
    await page.screenshot({ path: '.runtime/files-platform-light.png', animations: 'disabled' })
  } finally {
    execFileSync(python, ['-c', "import sys;sys.path.insert(0,'backend');from app.db import pool,transaction;pool.open(wait=True)\nwith transaction(admin=True) as c:c.execute(\"UPDATE users SET role='user' WHERE username=%s\",(sys.argv[1],))\npool.close()", username])
  }
  expect(errors).toEqual([])
})
